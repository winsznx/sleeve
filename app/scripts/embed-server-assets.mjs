#!/usr/bin/env node
// Writes src/generated/*.ts from the files server code reads to draw cards and to show the issuer disclosure, so that
// code imports them and reads no file at run time. Cloudflare Workers has no file system for them (D-033).
// src/generated/server-assets.test.ts fails while any output is stale. Run after changing a source:
//   node scripts/embed-server-assets.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const app = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(app, 'src', 'generated');

const FONT_DIR = 'src/components/cards/fonts';
const LOGO_DIR = 'public/assets/tokens';
const LOGO_EXTENSIONS = new Set(['.png', '.jpg', '.svg']);

function header(sources) {
  return `// Generated by scripts/embed-server-assets.mjs from ${sources}. Do not edit by hand.\n`;
}

function read(relative) {
  return readFileSync(path.join(app, relative));
}

function textModule(name, relative) {
  return `${header(relative)}\nexport const ${name}: string = ${JSON.stringify(read(relative).toString('utf8'))};\n`;
}

function base64Module(name, typeName, dir, files, keyOf) {
  const keys = files.map(keyOf);
  const entries = files.map((file, index) => `  ${JSON.stringify(keys[index])}: ${JSON.stringify(read(path.join(dir, file)).toString('base64'))},`);
  return (
    `${header(dir)}\n` +
    `export type ${typeName} = ${keys.map((key) => JSON.stringify(key)).join(' | ')};\n\n` +
    `/** Each file's bytes in base64, by ${typeName === 'CardFontFile' ? 'file name' : 'the path the site serves it at'}. */\n` +
    `export const ${name}: Readonly<Record<${typeName}, string>> = {\n${entries.join('\n')}\n};\n`
  );
}

const fonts = readdirSync(path.join(app, FONT_DIR)).filter((file) => file.endsWith('.ttf')).sort();
const logos = readdirSync(path.join(app, LOGO_DIR)).filter((file) => LOGO_EXTENSIONS.has(path.extname(file))).sort();

const outputs = {
  'tokens-css.ts': textModule('TOKENS_CSS', 'src/styles/tokens.css'),
  'disclosure-text.ts': textModule('DISCLOSURE_TEXT', 'public/disclosure/rhj-disclosure.txt'),
  'card-fonts.ts': base64Module('CARD_FONTS', 'CardFontFile', FONT_DIR, fonts, (file) => file),
  'token-logos.ts': base64Module('TOKEN_LOGOS', 'TokenLogoPath', LOGO_DIR, logos, (file) => `/assets/tokens/${file}`),
};

mkdirSync(target, { recursive: true });
for (const [file, contents] of Object.entries(outputs)) writeFileSync(path.join(target, file), contents);
console.log(`wrote ${Object.keys(outputs).length} modules (${fonts.length} fonts, ${logos.length} logos) to ${path.relative(app, target)}`);
