#!/usr/bin/env node
/**
 * Installs the brand kit into the app, as the kit's README lays out (D-037). The kit lives in internal/brand-kit,
 * which is gitignored; its source/build.py builds every file from brand.json. Run this after every kit rebuild:
 *
 *   node scripts/install-brand-kit.mjs
 *
 * Besides copying the kit's files, it writes src/generated/brand/brand-art.ts: the logo's paths for the images the
 * card renderer draws (share cards and link previews). Satori cannot read the CSS variables the in-app logo uses, so
 * those images fill the same paths from their own palette. Nothing it writes is edited by hand: change brand.json,
 * rebuild the kit, then run this again.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const KIT = path.join(APP, '..', 'internal', 'brand-kit');

/** Kit file, then where it goes in the app (the kit README's table, under src/ and public/). */
const FILES = [
  ['react/SleeveLogo.tsx', 'src/generated/brand/sleeve-logo.tsx'],
  ['react/sleeve-logo.css', 'src/generated/brand/sleeve-logo.css'],
  ['favicon/favicon.svg', 'src/app/icon.svg'],
  ['favicon/favicon.ico', 'src/app/favicon.ico'],
  ['favicon/apple-touch-icon.png', 'src/app/apple-icon.png'],
  ['favicon/icon-192.png', 'public/icon-192.png'],
  ['favicon/icon-512.png', 'public/icon-512.png'],
  ['favicon/icon-maskable-512.png', 'public/icon-maskable-512.png'],
  ['favicon/site.webmanifest', 'public/site.webmanifest'],
];
/** Logo files and social images for the README, docs, slides and listings, served from /brand/. */
const PUBLIC_BRAND = { logo: /\.(svg|png)$/, social: /\.png$/ };
const VARIANTS = ['symbol', 'micro', 'wordmark', 'horizontal', 'stacked'];
/** One line of the ART table the kit's build writes into react/SleeveLogo.tsx. */
const ART_LINE =
  /^ {2}(symbol|micro|wordmark|horizontal|stacked): \{ viewBox: ("[^"]*"), ratio: ([0-9.]+), base: ("[^"]*"), share: ("[^"]*"), word: ("[^"]*") \},$/gm;

function fail(message) {
  console.error(`install-brand-kit: ${message}`);
  process.exit(1);
}

function install(from, to) {
  const source = path.join(KIT, from);
  if (!existsSync(source)) fail(`${path.relative(APP, source)} is missing; rebuild the kit with python3 source/build.py`);
  const target = path.join(APP, to);
  mkdirSync(path.dirname(target), { recursive: true });
  copyFileSync(source, target);
  return to;
}

function brandArt() {
  const brand = JSON.parse(readFileSync(path.join(KIT, 'brand.json'), 'utf8'));
  const tsx = readFileSync(path.join(KIT, 'react/SleeveLogo.tsx'), 'utf8');
  const art = {};
  for (const [, name, viewBox, ratio, base, share, word] of tsx.matchAll(ART_LINE)) {
    art[name] = { viewBox: JSON.parse(viewBox), ratio: Number(ratio), base: JSON.parse(base), share: JSON.parse(share), word: JSON.parse(word) };
  }
  const missing = VARIANTS.filter((name) => art[name] === undefined);
  if (missing.length > 0) fail(`react/SleeveLogo.tsx has no ART line for ${missing.join(', ')}; the kit's output format changed`);
  const entries = VARIANTS.map((name) => `  ${name}: ${JSON.stringify(art[name])},`).join('\n');
  return `// Generated by scripts/install-brand-kit.mjs from the brand kit's react/SleeveLogo.tsx. Do not edit by hand.

export type BrandArtName = ${VARIANTS.map((name) => `'${name}'`).join(' | ')};

export interface BrandArt {
  viewBox: string;
  /** Width over height. */
  ratio: number;
  /** The rounded square: the payment and the account. */
  base: string;
  /** The detached corner: the share set aside as stock. */
  share: string;
  word: string;
}

export const BRAND_KIT_VERSION: string = ${JSON.stringify(brand.version)};
/** Below this height in pixels the symbol uses the micro drawing. */
export const BRAND_MICRO_BELOW_PX: number = ${Number(brand.geometry.microBelowPx)};

export const BRAND_ART: Readonly<Record<BrandArtName, BrandArt>> = {
${entries}
};
`;
}

if (!existsSync(path.join(KIT, 'brand.json'))) fail(`no brand kit at ${path.relative(process.cwd(), KIT)}`);
const installed = FILES.map(([from, to]) => install(from, to));
for (const [folder, pattern] of Object.entries(PUBLIC_BRAND)) {
  for (const name of readdirSync(path.join(KIT, folder)).filter((file) => pattern.test(file)).sort()) {
    installed.push(install(`${folder}/${name}`, `public/brand/${name}`));
  }
}
const artFile = 'src/generated/brand/brand-art.ts';
writeFileSync(path.join(APP, artFile), brandArt());
installed.push(artFile);
console.log(`install-brand-kit: ${installed.length} files from brand kit ${JSON.parse(readFileSync(path.join(KIT, 'brand.json'), 'utf8')).version}`);
for (const file of installed) console.log(`  ${file}`);
